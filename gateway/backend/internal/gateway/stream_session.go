// errCodeStreamIdleTimeout and errCodeClientDisconnected are the two synthetic
// (never-hits-a-provider) terminal error codes a streamSession can classify a
// stream into, shared by recordUsage's errorCode column and each flavor's
// terminal-frame switch. They are distinct from any completionErrorCode value.
const (
	errCodeStreamIdleTimeout  = "provider.stream_idle_timeout"
	errCodeClientDisconnected = "provider.client_disconnected"
)

// streamSession holds the SSE lifecycle scaffold shared by completeStream,
// completeStreamResponses, and completeStreamAnthropic: resolve + active
// registration, response headers, the idle watchdog, the write-deadline-armed
// capture-teeing emit, terminal-status classification, and the recordUsage
// epilogue. Each of those functions keeps ONLY its own protocol frame shaping
// (chat.completion.chunk vs the Responses event sequence vs Anthropic's
// message_start/content_block_*/message_delta/message_stop events) and drives
// the shared machinery through this type's methods.
//
// A streamSession is used from a single goroutine (the request handler plus
// the synchronous provider-stream callback it drives) and is not safe for
// concurrent use from multiple goroutines.
type streamSession struct {
	s     *Server
	w     http.ResponseWriter
	r     *http.Request
	token auth.Token
	req   inference.Request // the original, client-facing request (echoed in frames)
	raw   []byte
	id    string
	start time.Time

	capturing bool
	target    routing.Target
	streamer  provider.StreamingClient
	flusher   http.Flusher

	providerReq inference.Request // req with target.ProviderModel applied, for the upstream call
	// baseCtx is ctx before the target's upstream credential is attached: the
	// cancellable stream context with its capture sink, from which a re-selected
	// target's ctx is built.
	baseCtx  context.Context
	ctx      context.Context
	cancel   context.CancelFunc
	rc       *http.ResponseController
	idle     time.Duration
	watchdog *time.Timer
	idledOut atomic.Bool

	respBuf     bytes.Buffer
	capBytes    int
	captureSink *provider.CaptureSink

	// progress is this request's live counter, shared by pointer with the
	// ActiveRequest registered in beginStream (same allocation) so the registry's
	// DTO builder sees values as this goroutine writes them. Always non-nil: this
	// is the one streaming path that has something to count.
	progress *requestProgress
}

// beginStream resolves the routing target, verifies the provider supports
// streaming and that w can flush, registers the request as Active, writes the
// SSE response headers, and arms the idle watchdog. On any failure along the
// way it writes the appropriate response itself, records usage, and returns
// (nil, false) — the caller must return immediately without further action.
//
// fallback is the ONE per-protocol hook in this otherwise-identical preamble:
// when w can't flush, begin falls back to the buffered s.complete path, and
// fallback renders that flavor's non-streaming success body. id must be
// generated by the caller (nextRequestID(), called exactly once per request)
// so a fallback closure built before begin runs can embed it in the body it
// renders.
func (s *Server) beginStream(w http.ResponseWriter, r *http.Request, token auth.Token, req inference.Request, raw []byte, id string, fallback func(provider.Response) any) (*streamSession, bool) {
	start := time.Now()
	capturing := s.capturingEnabled(token)
	target, err := s.resolveTranslateTarget(r, &token, req)
	if err != nil {
		// pre-stream failure: the client has no stream yet, so return a normal JSON error
		slog.Warn("inference stream resolve failed", "path", r.URL.Path, "api_flavor", req.APIFlavor, "model", req.Model, "code", completionErrorCode(err), "status", completionHTTPStatus(err), "err", err)
		body := writeCompletionErrorCaptured(w, err)
		s.recordUsage(start, token, req, routing.Target{}, provider.Response{}, completionErrorCode(err), "error", usageMeta{ReqPath: r.URL.Path, HTTPStatus: completionHTTPStatus(err), ContentType: "application/json"}, id, buildCaptureInput(capturing, token.UserID, token.Secret, r, raw, w.Header(), body, completionHTTPStatus(err), req.APIFlavor), nil)
		return nil, false
	}
	streamer, ok := s.Provider.(provider.StreamingClient)
	if !ok {
		body := writeJSONCaptured(w, http.StatusBadGateway, apierror.Response("provider.unavailable", "streaming not supported", ""))
		s.recordUsage(start, token, req, target, provider.Response{}, "provider.unavailable", "error", usageMeta{ReqPath: r.URL.Path, HTTPStatus: http.StatusBadGateway, ContentType: "application/json"}, id, buildCaptureInput(capturing, token.UserID, token.Secret, r, raw, w.Header(), body, http.StatusBadGateway, req.APIFlavor), nil)
		return nil, false
	}
	flusher, ok := w.(http.Flusher)
	if !ok {
		// Defensive: no flushing available — fall back to a buffered completion.
		// Registration happens inside complete (Stream:false), so this path is
		// tracked exactly once and never double-registered.
		s.complete(w, r, token, req, raw, fallback)
		return nil, false
	}

	// Register ONLY on the real streaming path (after the flusher check). The early
	// resolve-error and no-streamer branches above return before this and are
	// intentionally not tracked as active (they still record to the completed list).
	// progress is allocated here (the TRANSLATE path's only such site: of the three
	// production Add sites, inference_complete.go's buffered one has no frames to
	// count, and proxyNative allocates the other counter — for a STREAMING native
	// passthrough request — in native_passthrough.go) and the same pointer is
	// threaded into the streamSession below, so both the registry's copy and this
	// goroutine's writes share one live counter.
	progress := &requestProgress{}
	idle := s.streamIdleTimeout // 0 = disabled (unbounded; only client disconnect ends the stream)
	ctx, cancel := context.WithCancel(r.Context())
	ss := &streamSession{
		s: s, w: w, r: r, token: token, req: req, raw: raw, id: id, start: start,
		capturing: capturing, target: target, streamer: streamer, flusher: flusher,
		providerReq: s.upstreamRequest(r.Context(), target, req), ctx: ctx, cancel: cancel, rc: http.NewResponseController(w),
		idle: idle, capBytes: s.captureMaxBytes, progress: progress,
	}
	ss.register()

	markServedInstance(w, req, target)
	w.Header().Set("Content-Type", "text/event-stream")
	w.Header().Set("Cache-Control", "no-cache")
	w.Header().Set("Connection", "keep-alive")
	w.WriteHeader(http.StatusOK)

	if idle > 0 {
		ss.watchdog = time.AfterFunc(idle, func() { ss.idledOut.Store(true); cancel() })
	}
	// Thread a capture sink so the provider records the upstream response headers.
	// When capturing, it keeps the full translated request + raw upstream response.
	// For a vendor-account target that is NOT capturing, a header-only sink (respCap
	// 0, no body buffered) is still attached so the best-effort vendor rate-limit
	// scrape can read the upstream headers off a normal (uncaptured) stream.
	switch {
	case capturing:
		ss.captureSink = provider.NewCaptureSink(s.captureMaxBytes)
	case target.VendorAccountID != "":
		ss.captureSink = provider.NewCaptureSink(0)
	}
	if ss.captureSink != nil {
		ss.ctx = provider.WithCaptureSink(ss.ctx, ss.captureSink)
	}
	ss.baseCtx = ss.ctx
	// Attach the resolved application's per-app upstream credential (fail-open).
	ss.ctx = s.upstreamAuthCtx(ss.baseCtx, target)
	return ss, true
}

// register (re)registers the stream in the active registry under its one id, for
// the session's current target: an id added again moves to the new target's server
// and instance, so a re-selected stream counts once, where it now runs.
func (ss *streamSession) register() {
	s, r, token, req, target := ss.s, ss.r, ss.token, ss.req, ss.target
	s.Active.Add(ActiveRequest{ID: ss.id, UserID: token.UserID, TokenID: token.ID, TokenName: token.Name, ServiceID: token.ServiceID, ServiceName: token.ServiceName, ServerName: s.serverName(target.ServerID), ServerID: target.ServerID, InstanceKey: target.InstanceKey, Model: req.Model, RequestedModel: req.RequestedModel, APIFlavor: req.APIFlavor, BillingUnit: billingUnitFor(req.APIFlavor), ReqPath: r.URL.Path, ProviderPath: upstreamPath(target, req.APIFlavor, endpointChat), ProviderModel: effectiveProviderModel(target, req.Model), SessionID: req.ClientSessionID, SessionSource: req.SessionSource, AgentID: req.AgentID, Stream: true, StartedAt: ss.start, Progress: ss.progress})
}

// close releases the session's resources: it stops the idle watchdog, cancels
// the stream context, and removes the request from the Active list — in that
// order, mirroring the LIFO order of the equivalent defers this scaffold used
// to declare inline. The caller must `defer ss.close()` immediately after a
// successful beginStream.
func (ss *streamSession) close() {
	if ss.watchdog != nil {
		ss.watchdog.Stop()
	}
	ss.cancel()
	ss.s.Active.Remove(ss.id)
}

// emit is the single client-SSE write path: it re-arms the write deadline to a
// fresh idle window, writes frame verbatim, flushes, and — when capturing —
// tees the identical bytes into respBuf, bounded by capBytes (~1 MB even with
// the idle watchdog disabled; buildCaptureEnvelope then flags truncated and
// clips to the cap). armWrite -> write -> flush order is unchanged, and the tee
// append happens only after a successful write so the write deadline and frame
// ordering are untouched. respBuf is written only from this provider-stream
// goroutine (serial emit) so no mutex is needed.
func (ss *streamSession) emit(frame string) error {
	if ss.idle > 0 {
		_ = ss.rc.SetWriteDeadline(time.Now().Add(ss.idle))
	}
	if _, err := fmt.Fprint(ss.w, frame); err != nil {
		return err
	}
	ss.flusher.Flush()
	if ss.capturing && ss.respBuf.Len() <= ss.capBytes {
		ss.respBuf.WriteString(frame)
	}
	return nil
}

// stream drives the provider's CompleteStream with handler, resetting the idle
// watchdog on every event exactly like each flavor's inline callback used to
// (StreamEventError is unused: providers report failures via CompleteStream's
// return value, not events).
//
// A stream whose instance turns out to be gone before it delivered a single event
// is re-selected once onto another instance (reselect) and started there; the
// client, which has had the response headers and nothing else, sees one stream.
func (ss *streamSession) stream(handler func(inference.StreamEvent) error) error {
	delivered := false
	onEvent := func(ev inference.StreamEvent) error {
		delivered = true
		if ss.watchdog != nil {
			ss.watchdog.Reset(ss.idle)
		}
		// One hook for all three translate flavors: this wrapper is what
		// chat-completions, Responses and Anthropic translate all stream through.
		// Only a delta that actually carried content counts as "first token".
		if ev.Type == inference.StreamEventTextDelta && (ev.Text != "" || ev.Reasoning != "") {
			ss.progress.observeDelta(time.Now(), ev.Progress)
		}
		return handler(ev)
	}
	err := ss.streamer.CompleteStream(ss.ctx, ss.target, ss.providerReq, onEvent)
	if err != nil && !delivered && ss.reselect(err) {
		err = ss.streamer.CompleteStream(ss.ctx, ss.target, ss.providerReq, onEvent)
	}
	return err
}

// reselect moves the session onto a re-selected target when err says its instance
// is gone and the once-rule allows it (see instance_reselect.go), and reports whether
// it did. The lost attempt leaves the instance before the re-resolve -- its active row
// removed, which frees its count on the instance and its server and wakes a request
// parked for that server -- so a re-resolve that parks does not wait behind it. The
// session's request, token, target, upstream request and credential context then all
// become the re-selected attempt's, and it is registered again under its id on the
// new instance; the usage row finish records is that attempt's. A re-selection that
// fails registers the session where it was, so the stream ends with the original
// error, attributed to the instance that refused it.
//
// The idle watchdog beginStream armed is held while the selection runs and armed
// afresh after it. The selection may wait in the admission queue for the next
// instance -- bounded by the queue timeout and the client, as the first resolve was
// -- and that wait is not the stream going idle; the instance the stream is then sent
// to gets the whole first-byte budget the first one had. A watchdog that has already
// fired has ended the stream, which is then not re-selected.
func (ss *streamSession) reselect(err error) bool {
	if !reselectsLostInstance(ss.target, ss.req, err) {
		return false
	}
	if ss.watchdog != nil {
		if !ss.watchdog.Stop() {
			return false
		}
		defer ss.watchdog.Reset(ss.idle)
	}
	ss.s.Active.Remove(ss.id)
	req := withLostInstance(ss.req, ss.target)
	token := ss.token
	target, rerr := ss.s.resolveTranslateTarget(ss.r, &token, req)
	if rerr != nil {
		slog.Warn("inference stream: the routed instance is gone and re-selection failed", "path", ss.r.URL.Path, "model", ss.req.Model, "instance", ss.target.InstanceKey, "err", rerr)
		ss.register()
		return false
	}
	slog.Info("inference stream: the routed instance is gone; re-selected once", "path", ss.r.URL.Path, "model", ss.req.Model, "lost", ss.target.InstanceKey, "instance", target.InstanceKey)
	ss.req, ss.token, ss.target = req, token, target
	ss.providerReq = ss.s.upstreamRequest(ss.r.Context(), target, req)
	ss.ctx = ss.s.upstreamAuthCtx(ss.baseCtx, target)
	ss.register()
	return true
}

// terminalStatus classifies how the stream ended from the CompleteStream
// return value and the idle-watchdog/request-context state armed by
// beginStream, and returns the (status, errorCode) recordUsage expects along
// with clientGone (the disconnect race guard some flavors also need for their
// own post-switch decisions, e.g. completeStream's trailing [DONE]).
//
// clientGone is computed unconditionally, exactly once, up front — matching the
// original scaffold's single `clientGone := r.Context().Err() != nil &&
// !idledOut.Load()` — so it reflects the true disconnect state regardless of
// which case below fires; !idledOut guards the rare both-fired race (watchdog
// cancel racing a real client disconnect) so an idle timeout is never
// mislabeled as client-gone.
//
// It also logs the outcome — identical across all three translate flavors for
// the idle/disconnect/error cases; the success case is logged by the caller,
// which alone knows the flavor-specific usage/tool-call tallies to log.
func (ss *streamSession) terminalStatus(streamErr error) (status, errorCode string, clientGone bool) {
	clientGone = ss.r.Context().Err() != nil && !ss.idledOut.Load()
	switch {
	case streamErr == nil:
		return "success", "", clientGone
	case ss.idledOut.Load():
		slog.Error("inference stream idle timeout", "path", ss.r.URL.Path, "api_flavor", ss.req.APIFlavor, "model", ss.req.Model, "server", ss.s.serverName(ss.target.ServerID), "idle", ss.idle.String())
		return "error", errCodeStreamIdleTimeout, clientGone
	case clientGone:
		// Client disconnected — the socket is gone, so write no frame.
		slog.Debug("inference stream client disconnected", "path", ss.r.URL.Path, "api_flavor", ss.req.APIFlavor, "model", ss.req.Model, "server", ss.s.serverName(ss.target.ServerID))
		return "error", errCodeClientDisconnected, clientGone
	default:
		errorCode = completionErrorCode(streamErr)
		slog.Error("inference stream failed", "path", ss.r.URL.Path, "api_flavor", ss.req.APIFlavor, "model", ss.req.Model, "server", ss.s.serverName(ss.target.ServerID), "code", errorCode, "err", streamErr)
		return "error", errorCode, clientGone
	}
}

// finish runs the recordUsage/capture epilogue common to all three flavors: the
// SSE response headers (200, text/event-stream) were already written before
// streaming began, regardless of any mid-stream error, so both are always
// reported as such here. GenStart is the live progress counter's first-token
// stamp (zero for a tool-only stream): recordUsage uses it to derive a tokens/s
// for a vendor-account row whose provider reported none.
func (ss *streamSession) finish(usage inference.Usage, status, errorCode string) {
	streamCI := buildCaptureInput(ss.capturing, ss.token.UserID, ss.token.Secret, ss.r, ss.raw, ss.w.Header(), ss.respBuf.Bytes(), http.StatusOK, ss.req.APIFlavor)
	attachTranslatedCapture(streamCI, ss.captureSink)
	ss.s.recordUsage(ss.start, ss.token, ss.req, ss.target, provider.Response{Usage: usage}, errorCode, status, usageMeta{ReqPath: ss.r.URL.Path, HTTPStatus: http.StatusOK, ContentType: "text/event-stream", GenStart: ss.progress.firstTokenAt()}, ss.id, streamCI, ss.captureSink.ResponseHeaders())
}
